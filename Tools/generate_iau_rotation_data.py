#!/usr/bin/env python3
"""Generate pinned IAU coefficient tables from NAIF pck00011.tpc.

Standard library only. Parse numeric BODY assignments inside begindata blocks;
never ingest the historical examples in begintext comments. Not a PCK loader.
"""
import argparse
import hashlib
import re
from pathlib import Path

EXPECTED_SHA256 = "3dff7b1dbeceaa01f25467767d3fa25816051c85d162d1edf04acb310ee28bb1"
BODIES = {'19p_borrelly': 1000005, '9p_tempel_1': 1000093, 'adrastea': 515, 'amalthea': 505, 'ariel': 701, 'atlas': 615, 'belinda': 714, 'bianca': 708, 'callisto': 504, 'calypso': 614, 'ceres': 2000001, 'charon': 901, 'cordelia': 706, 'cressida': 709, 'davida': 2000511, 'deimos': 402, 'desdemona': 710, 'despina': 805, 'dione': 604, 'earth': 399, 'enceladus': 602, 'epimetheus': 611, 'eros': 2000433, 'europa': 502, 'galatea': 806, 'ganymede': 503, 'gaspra': 9511010, 'helene': 612, 'iapetus': 608, 'ida': 2431010, 'io': 501, 'itokawa': 2025143, 'janus': 610, 'juliet': 711, 'jupiter': 599, 'larissa': 807, 'lutetia': 2000021, 'mars': 499, 'mercury': 199, 'metis': 516, 'mimas': 601, 'miranda': 705, 'moon': 301, 'naiad': 803, 'neptune': 899, 'oberon': 704, 'ophelia': 707, 'pallas': 2000002, 'pan': 618, 'pandora': 617, 'phobos': 401, 'phoebe': 609, 'pluto': 999, 'portia': 712, 'prometheus': 616, 'proteus': 808, 'puck': 715, 'rhea': 605, 'rosalind': 713, 'saturn': 699, 'steins': 2002867, 'sun': 10, 'telesto': 613, 'tethys': 603, 'thalassa': 804, 'thebe': 514, 'titan': 606, 'titania': 703, 'triton': 801, 'umbriel': 702, 'uranus': 799, 'venus': 299, 'vesta': 2000004}

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("kernel", type=Path)
parser.add_argument("output", type=Path)
args = parser.parse_args()
raw = args.kernel.read_bytes()
if hashlib.sha256(raw).hexdigest() != EXPECTED_SHA256:
    raise SystemExit("Kernel hash differs from the reviewed 2022-12-27 pck00011.tpc")
text = raw.decode("ascii")
data = "\n".join(part.split("\\begintext")[0] for part in text.split("\\begindata")[1:])
number = r"[-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eEdD][-+]?\d+)?"
values = {}
for key, body in re.findall(r"(BODY\d+_\w+)\s*=\s*\((.*?)\)", data, re.S):
    values[key] = [float(x.replace("D", "e").replace("d", "e")) for x in re.findall(number, body)]
for key, value in re.findall(r"(BODY\d+_(?:MAX_PHASE_DEGREE|CONSTANTS_JED_EPOCH))\s*=\s*(" + number + r")", data):
    values[key] = [float(value)]

def array(coefficients):
    return "[" + ", ".join(repr(x) for x in coefficients) + "]"

lines = ["// SPDX-License-Identifier: Apache-2.0",
         "// Generated by Tools/generate_iau_rotation_data.py; do not edit by hand.",
         "// NAIF pck00011.tpc (2022-12-27), SHA256 " + EXPECTED_SHA256,
         "// IAU 2015 report + 2019 correction; Earth/Moon retain labelled legacy models.",
         "let iauRotationModels: [String: IAURotationModelData] = ["]
for name, body_id in BODIES.items():
    prefix = f"BODY{body_id}_"
    system = f"BODY{body_id // 100}_"
    width = int(values.get(system + "MAX_PHASE_DEGREE", [1])[0]) + 1
    phases = values.get(system + "NUT_PREC_ANGLES", [])
    assert len(phases) % width == 0
    provenance = ".legacy2009" if name in ("earth", "moon") else ".iau2015Corrected2019"
    lines.append(f'  "{name}": IAURotationModelData(naifID: {body_id}, provenance: {provenance}, referenceJulianDate: {values.get(prefix + "CONSTANTS_JED_EPOCH", [2451545.0])[0]!r},')
    for index, (base_key, harmonic_key, function, variable) in enumerate([
        ("POLE_RA", "NUT_PREC_RA", "sine", "centuries"),
        ("POLE_DEC", "NUT_PREC_DEC", "cosine", "centuries"),
        ("PM", "NUT_PREC_PM", "sine", "days"),
    ]):
        label = ["rightAscension", "declination", "primeMeridian"][index]
        lines.append(f"    {label}: IAUAngleSeries(polynomialDegrees: {array(values[prefix + base_key])}, variable: .{variable}, harmonics: [")
        for i, amplitude in enumerate(values.get(prefix + harmonic_key, [])):
            if amplitude == 0:
                continue
            phase = phases[i*width:(i+1)*width]
            assert len(phase) == width, (name, harmonic_key, i)
            lines.append(f"      IAUHarmonic(amplitudeDegrees: {amplitude!r}, phaseDegrees: {array(phase)}, function: .{function}),")
        lines.append("    ])" + (")," if index == 2 else ","))
lines.append("]")
args.output.write_text("\n".join(lines) + "\n")
print(f"Generated {len(BODIES)} models in {args.output}")
